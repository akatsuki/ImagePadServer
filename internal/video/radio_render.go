func radioLatencyKeyframeSeconds(mode string) string {
	switch strings.ToLower(strings.TrimSpace(mode)) {
	case "rtsp-low":
		return "2"
	case "rtsp-realtime":
		return "0.5"
	default:
		return "1"
	}
}

