// RadioTrackFileName is the on-disk name of a pre-rendered playlist track.
// MP4 keeps AAC global headers so downstream copy remuxes stay clean.
func RadioTrackFileName(trackID string) string {
	return "radio-track-" + trackID + ".mp4"
}

// RenderRadioTrack renders the audio visualizer for one playlist track into a
// single MP4 file (with black edge fades) and returns its absolute path. The
// heavy lifting is the same pipeline as RunAudioVisualizerHLS; only the
// output muxer and the edge fades differ. progress (nil ok) receives the
// render fraction (0..1).
func RenderRadioTrack(ctx context.Context, outDir, ffmpeg string, input AudioRenderInput, trackID string, preset QualityPreset, progress func(float64)) (string, error) {
	return renderRadioTrackCPU(ctx, outDir, ffmpeg, input, trackID, preset, progress)
}

// renderRadioTrackCPU is the production playlist renderer. It intentionally
// reuses the canonical CPU visualizer pipeline so the playlist path has the
// same base-artwork, dynamic-layer, ASS, encoder, and mux behavior as the
// established CPU reference path. GPU sidecar code remains diagnostic-only.
func renderRadioTrackCPU(ctx context.Context, outDir, ffmpeg string, input AudioRenderInput, trackID string, preset QualityPreset, progress func(float64)) (string, error) {
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return "", fmt.Errorf("create CPU radio output directory: %w", err)
	}
	outPath := filepath.Join(outDir, RadioTrackFileName(trackID))
	buildArgs := func(assPath, fontDir string, mode *ForegroundMode, encoder VideoEncoderProfile) []string {
		recipe := NewRadioRenderRecipe(preset, encoder, audioLoudnormFilter(input.Kind), input.Analysis.Duration)
		recipe.SourcePath = input.SourcePath
		recipe.ASSPath = assPath
		recipe.FontDir = fontDir
		recipe.OutputPath = outPath
		return recipe.FFmpegArgs(mode)
	}
	cleanup := func() {
		_ = os.Remove(outPath)
	}
	if err := runAudioVisualizerEncode(ctx, outDir, ffmpeg, input, trackID, preset, EncoderLowLatency, buildArgs, cleanup, progress); err != nil {
		return "", fmt.Errorf("CPU radio render: %w", err)
	}
	return outPath, nil
}

// renderRadioTrackGPU feeds wgpu-produced RGBA frames directly to FFmpeg's
// existing H.264/AAC mux path. Audio remains the source file; visuals are
// generated by the sidecar at the render clock, so showwaves/showfreqs/ASS are
// not applied a second time.
func renderRadioTrackGPU(ctx context.Context, outDir, ffmpeg, sidecarExe string, input AudioRenderInput, trackID string, preset QualityPreset, progress func(float64)) (string, error) {
	if os.Getenv("IMAGEPAD_GPU_H264_REQUIRED") == "1" {
		return renderRadioTrackGPUDirectH264(ctx, outDir, ffmpeg, sidecarExe, input, trackID, preset, progress)
	}
	outPath := filepath.Join(outDir, RadioTrackFileName(trackID))
	width, height := radioFallbackOutputSize(preset)
	encoder := SelectVideoEncoder(ctx, ffmpeg, EncoderLowLatency)
	args := []string{"-hide_banner", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgba", "-s", fmt.Sprintf("%dx%d", width, height), "-r", "30", "-i", "pipe:0", "-i", input.SourcePath, "-map", "0:v:0", "-map", "1:a:0", "-t", strconv.FormatFloat(input.Analysis.Duration, 'f', 3, 64)}
	args = append(args, encoder.FFmpegArgs(preset, "veryfast")...)
	args = append(args, "-c:a", "aac", "-ar", "48000", "-ac", "2", "-movflags", "+faststart", outPath)
	cmd := exec.CommandContext(ctx, ffmpeg, args...)
	hideWindow(cmd)
	inPipe, err := cmd.StdinPipe()
	if err != nil {
		return "", err
	}
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Start(); err != nil {
		return "", err
	}
	sidecar, err := StartSidecar(ctx, sidecarExe, "music-"+trackID)
	if err != nil {
		_ = cmd.Process.Kill()
		return "", fmt.Errorf("%w: start sidecar: %v", ErrGPURendererUnavailable, err)
	}
	defer sidecar.Close()
	if err := sidecar.Hello(ctx, "music-"+trackID); err != nil {
		_ = cmd.Process.Kill()
		return "", fmt.Errorf("%w: sidecar hello: %v", ErrGPURendererUnavailable, err)
	}
	sceneBuilder := NewCanonicalMusicSceneBuilder(input)
	frames := int(math.Ceil(input.Analysis.Duration * 30))
	if frames < 1 {
		frames = 1
	}
	for i := 0; i < frames; i++ {
		ptsNS := int64(float64(i) * float64(time.Second) / 30)
		scene := sceneBuilder.Scene(uint64(i), ptsNS)
		frame, err := sidecar.RenderScene(ctx, uint32(width), uint32(height), uint64(i), ptsNS, &scene)
		if err != nil {
			_ = cmd.Process.Kill()
			return "", fmt.Errorf("%w: render frame: %v", ErrGPURendererUnavailable, err)
		}
		packed, err := GPUFrameToPackedRGBA(frame)
		if err != nil {
			_ = cmd.Process.Kill()
			return "", fmt.Errorf("%w: pack frame: %v", ErrGPURendererUnavailable, err)
		}
		if _, err := inPipe.Write(packed); err != nil {
			_ = cmd.Process.Kill()
			return "", err
		}
		if progress != nil {
			progress(float64(i+1) / float64(frames))
		}
	}
	_ = inPipe.Close()
	if err := cmd.Wait(); err != nil {
		return "", fmt.Errorf("GPU radio render: %w: %s", err, trimOutput(stderr.Bytes()))
	}
	return outPath, nil
}

// renderRadioTrackGPUDirectH264 consumes compressed H.264 access units from
// the sidecar's D3D12/NVENC route and copy-muxes them with the source audio.
// This path is deliberately opt-in until the sidecar advertises the complete
// production contract. It never accepts a pixel frame and never falls back to
// RGBA, CPU YUV packing, or libx264.
func renderRadioTrackGPUDirectH264(ctx context.Context, outDir, ffmpeg, sidecarExe string, input AudioRenderInput, trackID string, preset QualityPreset, progress func(float64)) (string, error) {
	totalStarted := time.Now()
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return "", fmt.Errorf("create direct H264 output directory: %w", err)
	}
	outPath := filepath.Join(outDir, RadioTrackFileName(trackID))
	width, height := radioFallbackOutputSize(preset)
	args := directH264MuxArgs(input.SourcePath, outPath, width, height, input.Analysis.Duration)
	cmd := exec.CommandContext(ctx, ffmpeg, args...)
	hideWindow(cmd)
	inPipe, err := cmd.StdinPipe()
	if err != nil {
		return "", err
	}
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	ffmpegStart := time.Now()
	if err := cmd.Start(); err != nil {
		return "", err
	}
	gpuStageLog("go_ffmpeg_start seconds=%.6f", time.Since(ffmpegStart).Seconds())
	sidecarStart := time.Now()
	sidecar, err := StartSidecar(ctx, sidecarExe, "music-h264-"+trackID)
	if err != nil {
		_ = cmd.Process.Kill()
		_ = cmd.Wait()
		return "", fmt.Errorf("%w: start direct H264 sidecar: %v", ErrGPURendererUnavailable, err)
	}
	gpuStageLog("go_sidecar_start seconds=%.6f", time.Since(sidecarStart).Seconds())
	defer sidecar.Close()
	helloStarted := time.Now()
	if err := sidecar.Hello(ctx, "music-h264-"+trackID); err != nil {
		_ = cmd.Process.Kill()
		_ = cmd.Wait()
		return "", fmt.Errorf("%w: direct H264 sidecar hello: %v", ErrGPURendererUnavailable, err)
	}
	gpuStageLog("go_sidecar_hello seconds=%.6f backend=%s", time.Since(helloStarted).Seconds(), sidecar.Diagnostics().Backend)
	if err := sidecar.RequireH264Output(); err != nil {
		_ = cmd.Process.Kill()
		_ = cmd.Wait()
		return "", fmt.Errorf("%w: direct H264 output required: %v", ErrGPURendererUnavailable, err)
	}
	timelineStarted := time.Now()
	assets, timeline, err := CompilePlaylistGPUTrack(input, trackID)
	if err != nil {
		_ = cmd.Process.Kill()
		_ = cmd.Wait()
		return "", fmt.Errorf("%w: compile playlist GPU timeline: %v", ErrGPURendererUnavailable, err)
	}
	gpuStageLog("go_playlist_timeline_compile seconds=%.6f assets_hash=%s timeline_hash=%s", time.Since(timelineStarted).Seconds(), assets.AssetsHash, timeline.TimelineHash)
	playlistTimelineMode := os.Getenv("IMAGEPAD_GPU_PLAYLIST_TIMELINE") == "1"
	if playlistTimelineMode {
		prepareStarted := time.Now()
		if err := sidecar.PreparePlaylistTrack(ctx, 1, assets, playlistGPUSurfaceWidth, playlistGPUSurfaceHeight, timeline.FPS); err != nil {
			_ = cmd.Process.Kill()
			_ = cmd.Wait()
			return "", fmt.Errorf("%w: prepare playlist GPU track: %v", ErrGPURendererUnavailable, err)
		}
		gpuStageLog("go_playlist_prepare_track seconds=%.6f", time.Since(prepareStarted).Seconds())
	}
	builderStarted := time.Now()
	var sceneBuilder *CanonicalMusicSceneBuilder
	if !playlistTimelineMode {
		sceneBuilder = NewCanonicalMusicSceneBuilder(input)
		gpuStageLog("go_scene_builder seconds=%.6f", time.Since(builderStarted).Seconds())
	}
	frames := int(timeline.FrameCount)
	if frames < 1 {
		return "", fmt.Errorf("%w: compiled playlist GPU timeline has no frames", ErrGPURendererUnavailable)
	}
	var sceneBuildTotal, rpcTotal, pipeWriteTotal time.Duration
	batchCount := 0
	var bitstreamBytes int64
	for i := 0; i < frames; {
		batchEnd := i + GPUH264MaxBatchFrames
		if batchEnd > frames {
			batchEnd = frames
		}
		rpcStarted := time.Now()
		var encoded []EncodedH264Frame
		if playlistTimelineMode {
			chunk := TimelineChunk{
				ScrollProfiles: timeline.ScrollProfiles,
				Frames:         append([]FrameDirective(nil), timeline.Frames[i:batchEnd]...),
			}
			encoded, err = sidecar.RenderPlaylistTimelineBatch(ctx, uint64(batchCount), 1, assets.AssetsHash, timeline.TimelineVersion, chunk, nil)
		} else {
			batch := make([]H264RenderBatchFrame, 0, batchEnd-i)
			for frameIndex := i; frameIndex < batchEnd; frameIndex++ {
				ptsNS := timeline.Frames[frameIndex].PTSNs
				sceneStarted := time.Now()
				scene := sceneBuilder.Scene(uint64(frameIndex), ptsNS)
				sceneBuildTotal += time.Since(sceneStarted)
				batch = append(batch, H264RenderBatchFrame{
					Sequence: uint64(frameIndex),
					PTSNS:    ptsNS,
					Scene:    &scene,
				})
			}
			encoded, err = sidecar.RenderSceneH264Batch(ctx, uint32(width), uint32(height), batch)
		}
		rpcTotal += time.Since(rpcStarted)
		if err != nil {
			_ = cmd.Process.Kill()
			return "", fmt.Errorf("%w: direct H264 batch starting frame %d: %v", ErrGPURendererUnavailable, i, err)
		}
		batchCount++
		for offset, frame := range encoded {
			frameIndex := i + offset
			pipeStarted := time.Now()
			if _, err := inPipe.Write(frame.Payload); err != nil {
				_ = inPipe.Close()
				waitErr := cmd.Wait()
				return "", fmt.Errorf("%w: write direct H264 frame %d: %v; ffmpeg_wait=%v; ffmpeg_stderr=%s", ErrGPURendererUnavailable, frameIndex, err, waitErr, trimOutput(stderr.Bytes()))
			}
			pipeWriteTotal += time.Since(pipeStarted)
			bitstreamBytes += int64(len(frame.Payload))
			if progress != nil {
				progress(float64(frameIndex+1) / float64(frames))
			}
		}
		i = batchEnd
	}
	flushStarted := time.Now()
	if err := sidecar.FlushH264(ctx); err != nil {
		_ = cmd.Process.Kill()
		_ = inPipe.Close()
		waitErr := cmd.Wait()
		return "", fmt.Errorf("%w: direct H264 flush: %v; ffmpeg_wait=%v; ffmpeg_stderr=%s", ErrGPURendererUnavailable, err, waitErr, trimOutput(stderr.Bytes()))
	}
	gpuStageLog("go_h264_flush seconds=%.6f", time.Since(flushStarted).Seconds())
	gpuStageLog("go_frame_totals frames=%d batches=%d batch_size_max=%d scene_build_seconds=%.6f rpc_seconds=%.6f pipe_write_seconds=%.6f bitstream_bytes=%d", frames, batchCount, GPUH264MaxBatchFrames, sceneBuildTotal.Seconds(), rpcTotal.Seconds(), pipeWriteTotal.Seconds(), bitstreamBytes)
	pipeCloseStarted := time.Now()
	if err := inPipe.Close(); err != nil {
		waitErr := cmd.Wait()
		return "", fmt.Errorf("close direct H264 pipe: %w; ffmpeg_wait=%v; ffmpeg_stderr=%s", err, waitErr, trimOutput(stderr.Bytes()))
	}
	gpuStageLog("go_ffmpeg_stdin_close seconds=%.6f", time.Since(pipeCloseStarted).Seconds())
	muxWaitStarted := time.Now()
	if err := cmd.Wait(); err != nil {
		return "", fmt.Errorf("direct H264 mux: %w: %s", err, trimOutput(stderr.Bytes()))
	}
	gpuStageLog("go_ffmpeg_mux_wait seconds=%.6f total_seconds=%.6f", time.Since(muxWaitStarted).Seconds(), time.Since(totalStarted).Seconds())
	return outPath, nil
}

